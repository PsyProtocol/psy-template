#[tokio::test]
#[ignore = "Builds two actual NFT descriptor keys and proves their noninterchangeability; run serially"]
async fn prepared_nft_and_legacy_acknowledgement_keys_are_not_interchangeable() -> Result<()> {
    let spec = fixture("nftmarket")?; let prepared = batch_compact::build(&spec)?;
    let mut legacy = spec.clone();
    let index = legacy["operations"].as_array().context("NFT operations")?.iter()
        .position(|op| op["name"] == "activate").context("NFT activation")?;
    let collection = legacy["config"]["nftId"].clone();
    legacy["operations"][index]["calls"][2] = json!({"contract_id":collection,
        "method_id":1344479563u32,"method_name":"acknowledge","inputs":[{"witness":1}]});
    legacy["branches"][index + 2]["calls"] = legacy["operations"][index]["calls"].clone();
    ensure!(core_scope::anchor(&legacy).is_err(), "prepared core scope accepted legacy startup");
    // Explicit negative-control key only: no deployment or legacy admission.
    // The generic v2 builder constructs its real different circuit identity.
    let old = batch_compact::build(&legacy)?;
    ensure!(old.get_fingerprint() != prepared.get_fingerprint(), "startup descriptor change must use a new key");
    let fields = operation_fields(&spec["operations"][index])?;
    prove_stack(&prepared, &spec, &fields, 0).await?;
    prove_stack(&old, &legacy, &fields, 0).await?;
    ensure!(prove_stack(&old, &spec, &fields, 0).await.is_err(), "legacy key authorized prepare_account");
    ensure!(prove_stack(&prepared, &legacy, &fields, 0).await.is_err(), "prepared key authorized legacy acknowledge");
    println!("CORE_NFT_KEYS prepared {} legacy {}; synthetic signature proofs only; broadcast=false", prepared.get_fingerprint(), old.get_fingerprint());
    Ok(())
}
