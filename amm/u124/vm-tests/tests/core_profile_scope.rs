fn field(n: u64) -> F { F::from_canonical_u64(n) }
fn read(root: &Path, name: &str) -> Result<Value> {
    serde_json::from_slice(&fs::read(root.join(name))?).with_context(|| format!("fixture {name}"))
}
fn check_hash(root: &Path, name: &str, expected: &Value) -> Result<()> {
    let bytes = fs::read(root.join(name))?;
    ensure!(expected.as_str() == Some(format!("{:x}", Sha256::digest(bytes)).as_str()),
        "preserved fixture hash differs: {name}");
    Ok(())
}

/// Fixture manifests are local reproducibility inputs, not network trust roots.
/// Require generated bytecode, original build hashes and actual ABI selectors;
/// do not fall back to a fabricated accepted policy when fixtures are missing.
fn fixture(kind: &str) -> Result<Value> {
    let env = match kind { "bondingcurve" => "CORE_CURVE_BUILD", "orderbook" => "CORE_BOOK_BUILD",
        "nftmarket" => "CORE_NFT_BUILD", _ => anyhow::bail!("unsupported fixture market") };
    let path = std::env::var(env).with_context(|| format!("{env} must name a fresh compiled build root"))?;
    let root = Path::new(&path);
    let manifest = read(root, "BUILD.json")?;
    ensure!(manifest["sdkCommit"] == psy_template_u124_markets::sdk_release::SDK_COMMIT
        && manifest["clientCommit"] == psy_template_u124_markets::sdk_release::CLIENT_COMMIT,
        "fixture release differs from compiled release");
    let policy_path = format!("{kind}/policy.json");
    let artifact_path = format!("{kind}/compiled/compilation_artifact.json");
    check_hash(root, &policy_path, &manifest["policySha256"])?;
    check_hash(root, &artifact_path, &manifest["artifactSha256"])?;
    check_hash(root, &format!("{kind}/main.psy.rs"), &manifest["sourceSha256"])?;
    let audit_path = format!("{kind}/compiled/FOREIGN_READ_AUDIT.json");
    check_hash(root, &audit_path, &manifest["foreignReadAuditSha256"])?;
    let policy = read(root, &policy_path)?;
    ensure!(policy["market"] == kind && policy["market_id"] == manifest["declaredMarketId"]
        && policy["chain_root_at1"] == manifest["chainRootAt1"]
        && policy["config"] == manifest["inputs"]["config"]
        && policy["config"] == read(root, &format!("{kind}/config.json"))?,
        "actual fixture identities/configuration differ");
    let native = read(root, "native.json")?;
    // This frozen Native artifact deliberately supplies a layout-only ABI.
    // Its authenticated method selectors and arities come from the hashed
    // circuit_definitions, not an invented ABI method table.
    let native_contract = native["abi"]["contract"].as_object()
        .with_context(|| format!("{kind}: frozen Native layout-only ABI contract"))?;
    ensure!(native_contract.len() == 2 && native_contract.contains_key("state_layout")
        && native_contract.contains_key("state_tree_height")
        && native_contract["state_layout"].is_object(),
        "{kind}: exact frozen Native layout-only ABI format required");
    let token = read(root, "token/compilation_artifact.json")?;
    let market = read(root, &artifact_path)?;
    let nft = kind == "nftmarket";
    let roles = if nft { ["native", "paymentToken", "collection"] } else { ["native", "tokenA", "tokenB"] };
    let other_path = if nft { "nft/compilation_artifact.json" } else { "token-b/compilation_artifact.json" };
    for (name, role) in [("native.json", roles[0]), ("token/compilation_artifact.json", roles[1]), (other_path, roles[2])] {
        check_hash(root, name, &manifest["inputs"][role]["sha256"])?;
    }
    let other = read(root, other_path)?;
    let config = &policy["config"];
    let a = config[if nft { "tokenId" } else { "assetA" }].as_u64().context("asset A")?;
    let b = config[if nft { "nftId" } else { "assetB" }].as_u64().context("asset B")?;
    let m = policy["market_id"].as_u64().context("market")?;
    let artifacts = BTreeMap::from([(0, (&native, 32u64)), (a, (&token, 31)),
        (b, (&other, if nft { 30 } else { 31 })), (m, (&market, 31))]);
    for (artifact, height) in artifacts.values() {
        ensure!(artifact["state_tree_height"] == *height
            && artifact["abi"]["contract"]["state_tree_height"] == *height,
            "actual artifact tree height differs");
        ensure!(artifact["circuit_definitions"].as_array().is_some_and(|a| !a.is_empty()),
            "actual compiled circuit definitions required; ABI-only fixture is insufficient");
    }
    let mut calls = vec![&policy["begin"], &policy["finish"], &policy["expire"], &policy["noop"], &policy["burn"]];
    calls.extend(policy["commit"].as_array().context("commit calls")?);
    for op in policy["operations"].as_array().context("operations")? {
        calls.extend(op["calls"].as_array().context("operation calls")?);
    }
    for call in calls {
        let cid = call["contract_id"].as_u64().with_context(|| format!("{kind}: call contract"))?;
        let name = call["method_name"].as_str().with_context(|| format!("{kind}/{cid}: method name"))?;
        let inputs = call["inputs"].as_array().with_context(|| format!("{kind}/{cid}/{name}: descriptor inputs"))?;
        let (artifact, _) = artifacts.get(&cid)
            .with_context(|| format!("{kind}/{cid}/{name}: call outside actual fixture whitelist"))?;
        if cid != 0 {
            let methods = artifact["abi"]["contract"]["methods"].as_array()
                .with_context(|| format!("{kind}/{cid}/{name}: non-Native ABI methods required"))?;
            let matches = methods.iter().filter(|method| method["name"] == call["method_name"]).collect::<Vec<_>>();
            ensure!(matches.len() == 1, "{kind}/{cid}/{name}: unique actual ABI method required");
            ensure!(matches[0]["method_id"] == call["method_id"]
                && matches[0]["input_felt_count"].as_u64() == Some(inputs.len() as u64)
                && matches[0]["output_felt_count"] == 0,
                "{kind}/{cid}/{name}: descriptor differs from actual compiled ABI");
        }
        // Every call, including Native, must match the preserved compiled
        // function definition. Layout-only ABI never bypasses this check.
        let definitions = artifact["circuit_definitions"].as_array()
            .with_context(|| format!("{kind}/{cid}/{name}: compiled definitions"))?;
        let compiled = definitions.iter().filter(|d| d["name"] == call["method_name"]).collect::<Vec<_>>();
        ensure!(compiled.len() == 1 && compiled[0]["method_id"] == call["method_id"]
            && compiled[0]["circuit_inputs"].as_array().map(|a| a.len()) == Some(inputs.len())
            && compiled[0]["circuit_outputs"].as_array().is_some_and(|a| a.is_empty()),
            "{kind}/{cid}/{name}: descriptor differs from actual hashed compiled function definition");
    }
    let audit = read(root, &audit_path)?;
    ensure!(audit["allReadsBound"] == true && audit["assetA"] == a && audit["assetB"] == b
        && audit["assetAHeight"] == 31 && audit["assetBHeight"] == (if nft { 30 } else { 31 })
        && audit["nativeHeight"] == 32, "actual foreign-read audit differs");
    ensure!(audit["foreignReadCommandsChecked"].as_u64().is_some_and(|n| n > 0)
        && audit["financialOperations"] == 0,
        "positive integer foreign-read audit count and zero financial operations required");
    ensure!(core_scope::anchor(&policy)?.is_some(), "actual core policy must pass native scope");
    Ok(policy)
}

fn infos(spec: &Value, fields: &[u64]) -> Result<Vec<SDKeyTransactionInfo<F>>> {
    let descriptors = spec["branches"].as_array().context("coverage")?.iter()
        .flat_map(|b| b["calls"].as_array().unwrap()).chain([&spec["noop"], &spec["expire"]]).collect::<Vec<_>>();
    batch_policy::expected_calls(spec, fields)?.iter().map(|call| {
        let d = descriptors.iter().find(|d| d["contract_id"] == call["contract_id"]
            && d["method_name"] == call["method_name"]).context("actual descriptor")?;
        let args = call["inputs"].as_array().context("call args")?.iter()
            .map(|v| v.as_u64().map(field).context("call field")).collect::<Result<Vec<_>>>()?;
        Ok(DPNProvingSessionCompactMethodCall::new_from_inputs::<PoseidonHash>(
            field(DEFAULT_CALLER_CONTRACT_ID_U64), field(call["contract_id"].as_u64().unwrap()),
            field(d["method_id"].as_u64().unwrap()), &args).into())
    }).collect()
}

fn operation_fields(op: &Value) -> Result<Vec<u64>> {
    let mut fields = vec![0; 74];
    fields[0] = if op["maintenance"] == true { 4 } else { 2 };
    if fields[0] == 2 { fields[1] = 1; }
    fields[21] = op["branch"].as_u64().context("operation branch")?;
    for c in op["calls"].as_array().context("calls")? {
        for a in c["inputs"].as_array().context("inputs")? {
            if let Some(i) = a["witness"].as_u64() { fields[21 + i as usize] = 100 + i; }
        }
    }
    fields[73] = 1_000_000_000;
    Ok(fields)
}

async fn prove_stack(g: &SDKeyCircuitGadget, spec: &Value, fields: &[u64], attack: usize) -> Result<()> {
    let mut logical = infos(spec, fields)?;
    let noop = |c: &SDKeyTransactionInfo<F>| c.contract_id == field(spec["noop"]["contract_id"].as_u64().unwrap())
        && c.method_id == field(spec["noop"]["method_id"].as_u64().unwrap());
    let mut actual = logical.iter().filter(|c| !noop(c)).copied().collect::<Vec<_>>();
    ensure!(actual.len() >= 2, "attack vector requires a real nontrivial stack");
    let first_active = logical.iter().position(|c| !noop(c)).context("first actual call")?;
    let user = PsyUserLeaf { user_id: field(123), last_checkpoint_id: field(7), ..Default::default() };
    let mut end = user; end.nonce = field(1);
    let mut start = user.qfhash::<PoseidonHash>();
    let mut cp = QHashOut(HashOut::ZERO); let mut tree = cp; let mut domain = PSY_NETWORK_MAGIC;
    match attack {
        1 => actual[0].contract_id = field(999),
        2 => { actual.pop(); },
        3 => actual.push(actual[0]),
        4 => end.nonce = field(2),
        5 => end.user_state_tree_root = QHashOut(HashOut { elements: [field(7); 4] }),
        6 => start = QHashOut(HashOut { elements: [field(8); 4] }),
        7 => cp = QHashOut(HashOut { elements: [field(9); 4] }),
        8 => tree = QHashOut(HashOut { elements: [field(10); 4] }),
        9 => domain += 1,
        10 => { let n = logical.iter().find(|c| noop(c)).context("canonical noop")?; actual.insert(1, *n); },
        11 => { logical[first_active].caller_contract_id = field(12); actual[0].caller_contract_id = field(12); },
        12 => actual.swap(0, 1),
        // Both declared stack and signature carry the same altered input hash;
        // the policy's approved argument commitment must still reject it.
        13 => { logical[first_active].inputs_hash = QHashOut(HashOut { elements: [field(11); 4] }); actual[0] = logical[first_active]; },
        14 => { logical.last_mut().context("burn slot")?.inputs_hash = QHashOut(HashOut { elements: [field(12); 4] });
            *actual.last_mut().context("actual burn")? = *logical.last().unwrap(); },
        _ => {}
    }
    let data = PsyUserProvingSessionSignatureDataCompact { start_user_leaf_hash: start,
        end_user_leaf_hash: end.qfhash::<PoseidonHash>(), checkpoint_leaf_hash: cp,
        tx_stack_hash: compute_tx_stack_hash(&actual), tx_count: field(actual.len() as u64) };
    let sig = data.get_sig_action_for_user::<PoseidonHash>(domain, field(123), end.nonce,
        SignContext::new(tree, user)).get_qhash::<PoseidonHash>();
    let input = SDKeyCircuitWitnessInput { session_context: SDKeySessionContext { start_user_leaf: user,
        start_user_leaf_hash: user.qfhash::<PoseidonHash>(), checkpoint_leaf_hash: QHashOut(HashOut::ZERO),
        checkpoint_tree_root: QHashOut(HashOut::ZERO), current_user_leaf: user, nonce: field(1) },
        circuit_inputs: fields.iter().copied().map(field).collect(), transaction_infos: logical,
        tx_stack_hash: compute_tx_stack_hash(&actual), tx_count: field(actual.len() as u64), state_reader_results: None,
        secp256k1_slots: vec![], checkpoint_id: field(7), user_id: field(123) };
    let proof = g.prove(QHashOut(HashOut { elements: [F::ONE; 4] }), &input, sig).await?;
    g.minifier_chain.as_ref().context("built compact verifier")?.verify(proof)?;
    Ok(())
}

#[test]
#[ignore = "Requires all three preserved fresh compiled fixture roots; no fabricated fallback"]
fn actual_generated_policies_pass_scope_and_reject_identity_coverage_changes() -> Result<()> {
    for kind in ["bondingcurve", "orderbook", "nftmarket"] {
        let spec = fixture(kind)?;
        for (key, value) in [("sdk_commit", json!("wrong")), ("client_commit", json!("wrong")),
            ("chain_root_at1", json!("0".repeat(64))), ("fee_max", json!("1000100001")),
            ("whole_market_completeness", json!(true)), ("qualified_randomness", json!(true))] {
            let mut bad = spec.clone(); bad[key] = value;
            ensure!(core_scope::anchor(&bad).is_err(), "accepted actual policy substitution {kind}/{key}");
        }
        let mut bad = spec.clone(); bad["branches"][0]["calls"][0]["method_id"] = json!(1);
        ensure!(core_scope::anchor(&bad).is_err(), "accepted altered actual dependency coverage");
    }
    Ok(())
}

async fn key_acceptance(kind: &str) -> Result<()> {
    let spec = fixture(kind)?; let key = batch_compact::build(&spec)?;
    let operations = spec["operations"].as_array().context("actual operations")?;
    for op in operations { prove_stack(&key, &spec, &operation_fields(op)?, 0).await?; }
    let activation = operations.iter().find(|op| op["name"] == if kind == "nftmarket" { "activate" } else { "activate_batch_vault" })
        .context("actual startup operation")?;
    let fields = operation_fields(activation)?;
    for attack in 1..=14 {
        ensure!(prove_stack(&key, &spec, &fields, attack).await.is_err(), "{kind} accepted stack/session attack {attack}");
    }
    let mut commit = vec![0; 74]; commit[0] = 1; commit[1] = 1; commit[2] = 2; commit[3] = 120;
    commit[4] = 300; commit[5] = 200; commit[6] = 201; commit[9] = 1; commit[10] = 2; commit[73] = 1_000_000_000;
    prove_stack(&key, &spec, &commit, 0).await?;
    let mut expire = vec![0; 74]; expire[0] = 3; expire[1] = 1; expire[73] = 1_000_000_000;
    prove_stack(&key, &spec, &expire, 0).await?;
    println!("CORE_PROFILE_KEY {kind}: actual policy; fingerprint {}; operation templates {}; 14 stack/session/argument/fee rejections; synthetic sessions only, not complete UPS/finality/network acceptance", key.get_fingerprint(), operations.len());
    Ok(())
}

